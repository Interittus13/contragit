export function renderTextToPixelMatrix(text: string): boolean[][] {
  const clean = text.toUpperCase().replace(/[^A-Z0-9 !+\-]/g, '');
  const rows: boolean[][] = Array.from({ length: 7 }, () => []);

  for (let i = 0; i < clean.length; i++) {
    const char = clean[i];
    const glyph = PIXEL_FONT[char] || PIXEL_FONT[' '];
    const glyphWidth = glyph[0].length;

    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < glyphWidth; c++) {
        rows[r].push(Boolean(glyph[r][c]));
      }
      // Add 1-column spacing between characters
      if (i < clean.length - 1) {
        rows[r].push(false);
      }
    }
  }

  return rows;
}
